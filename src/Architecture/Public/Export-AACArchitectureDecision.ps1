function Export-AACArchitectureDecision {
    <#
    .EXTERNALHELP Azure.Admin.Console-help.xml
    .SYNOPSIS
        Step 6: writes architecture decision records (Markdown) for the
        design - topology, each pattern, each accepted risk.
    .DESCRIPTION
        One numbered file per decision, plus README.md listing them with the
        open decisions and assumptions. Files of the same name are
        replaced. Offline.
    .PARAMETER Design
        The design, or the path of a saved one.
    .PARAMETER Path
        The folder to write to.
    .PARAMETER Accept
        Accepted risks: a rule ID or rule:component.
    .PARAMETER Reason
        Why the risks are accepted.
    .PARAMETER Owner
        Who owns the decisions.
    .PARAMETER ReviewBy
        When accepted risks are reviewed (90 days from now by default).
    .PARAMETER GuardrailPath
        Your guardrails.
    .EXAMPLE
        Export-AACArchitectureDecision -Design $design -Path .\adr -Owner 'Platform team'
        The records and README.md.
    .EXAMPLE
        Export-AACArchitectureDecision -Design $design -Path .\adr -Accept 'REL-MR-01' -Reason 'One region for phase 1'
        Also records an accepted risk.
    .OUTPUTS
        System.IO.FileInfo
    #>
    [CmdletBinding()]
    [OutputType([System.IO.FileInfo])]
    param(
        [Parameter(Mandatory, ValueFromPipeline)]
        [ValidateNotNull()]
        [object] $Design,

        [Parameter(Mandatory)]
        [string] $Path,

        [string[]] $Accept = @(),

        [string] $Reason = '',

        [string] $Owner = '',

        [datetime] $ReviewBy = (Get-Date).AddDays(90),

        [string] $GuardrailPath
    )

    process {
        trap { if ($_.Exception -is [System.Management.Automation.PipelineStoppedException]) { return }; $PSCmdlet.ThrowTerminatingError((Show-AACError -ErrorRecord $_ -Cmdlet $PSCmdlet)) }
        $resolve = { param([string] $Value) if ($Value) { $PSCmdlet.SessionState.Path.GetUnresolvedProviderPathFromPSPath($Value) } }
        $catalog = Get-AACArchitectureCatalog
        $model = Resolve-AACArchitectureInput -InputObject $(if ($Design -is [string]) { & $resolve $Design } else { $Design }) -Kind Design
        $guard = if ($GuardrailPath) { Read-AACArchitectureFile -Path (& $resolve $GuardrailPath) -What 'the guardrails' } else { @{} }
        $result = Invoke-AACArchitectureRule -Design $model -Catalog $catalog -Guardrail $guard -Accept $Accept
        $full = ConvertTo-AACArchitectureBrief -Catalog $catalog -Answer $model.Answers -Name $model.Name
        $ranked = @(ConvertTo-AACArchitecturePattern -Catalog $catalog -Answers $full.Answers)
        $folder = & $resolve $Path
        if (-not (Test-Path -LiteralPath $folder)) { New-Item -ItemType Directory -Path $folder -Force | Out-Null }
        $today = [datetime]::UtcNow.ToString('yyyy-MM-dd', [cultureinfo]::InvariantCulture)
        $a = $full.Answers
        $slug = { param([string] $Text) ($Text.ToLowerInvariant() -replace '[^a-z0-9]+', '-').Trim('-') }
        $records = [System.Collections.Generic.List[hashtable]]::new()
        $footer = "`n---`nDesign: $($model.Name) · catalog $($catalog.Version)$(if ($Owner) { " · owner: $Owner" }) · generated by Azure.Admin.Console $today`n"
        $write = {
            param([string] $Title, [string] $Status, [string] $Body)
            $number = '{0:D4}' -f ($records.Count + 1)
            $file = Join-Path -Path $folder -ChildPath "$number-$(& $slug $Title).md"
            [System.IO.File]::WriteAllText($file, "# $number. $Title`n`n- Status: $Status`n- Date: $today`n$(if ($Owner) { "- Owner: $Owner`n" })`n$Body$footer", [System.Text.UTF8Encoding]::new($false))
            $records.Add(@{ Number = $number; Title = $Title; Status = $Status; File = Split-Path -Path $file -Leaf })
            Get-Item -LiteralPath $file
        }
        $nodeList = { param([string[]] $Zone) (@($model.Nodes | Where-Object { $_.Zone -in $Zone -and $_.Region -in @(@($model.Regions)[0], '') } | ForEach-Object { "$($_.Name)$(if ($_.Sku) { " ($($_.Sku))" })" })) -join ', ' }

        # 0001 - hosting and topology.
        $body = @"
## Context

$($model.Name) is a $([string]$a['BUS-02']) $([string]$a['BUS-01']) workload: $([string]$a['SEC-01']) data, a $([string]$a['REL-03'])% SLA, RTO $([string]$a['REL-01']) minutes and RPO $([string]$a['REL-02']) minutes, exposure: $([string]$a['SEC-03']).

## Decision

- Compute and entry: $(& $nodeList 'Edge', 'Spoke')
- Data: $(& $nodeList 'Data')
- Integration: $(if (& $nodeList 'Integration') { & $nodeList 'Integration' } else { 'none' })
- Network: $(if (@($model.Nodes | Where-Object Kind -EQ 'network').Count) { 'hub and spoke' + $(if (@($model.Nodes | Where-Object Kind -EQ 'firewall').Count) { ', Azure Firewall for egress' } else { '' }) + $(if (@($model.Nodes | Where-Object Kind -EQ 'dns').Count) { ', private endpoints with private DNS in the hub' } else { '' }) } else { 'no virtual network (public PaaS endpoints)' })
- Regions: $(@($model.Regions) -join ' and ')$(if ($model.LandingZone) { " in the landing zone $($model.LandingZone)" })
- Deployment: $([string]$a['OPS-01'])$(if ($a['OPS-01'] -ne 'Manual') { ', with a PSRule for Azure gate before deployment' })

## Consequences

- Zone redundancy is $(if ([double]$a['REL-03'] -ge 99.95) { 'required on every zonal tier' } else { 'not required by the SLA' }); $(if (@($model.Regions).Count -gt 1) { 'a second region carries replicas and takes over through the entry point' } else { 'a regional outage takes the workload down until it is redeployed or restored' }).
- Inherited policy: $(if (@($model.Policies).Count) { (@($model.Policies | ForEach-Object { $_['Name'] })) -join '; ' } else { 'none read' }).
- Validation: $(@($result.Findings | Where-Object Status -EQ 'Open').Count) open finding(s) at the time of writing (Test-AACArchitectureDesign).
"@
        & $write 'Hosting and topology' 'Accepted' $body

        # One per pattern.
        foreach ($id in @($model.Patterns)) {
            $p = @($catalog.Patterns | Where-Object Id -EQ $id)[0]
            $r = @($ranked | Where-Object Id -EQ $id)[0]
            if (-not $p) { continue }
            $body = @"
## Context

$($p.Problem)

Why it fits: $(if ($r) { $r.Why } else { 'chosen by the team' }).

## Decision

Use the [$($p.Name)]($($p.Link)) pattern$(if (@($p.Adds).Count) { ", which adds: $(@($p.Adds) -join ', ')" }).

## Consequences

Well-Architected trade-offs: $(if ($r) { $r.TradeOffs } else { '' }).
"@
            & $write "Use $($p.Name)" 'Accepted' $body
        }

        # One per accepted risk.
        foreach ($f in @($result.Findings | Where-Object Status -EQ 'Accepted')) {
            $body = @"
## Context

$($f.Finding) - $($f.Component) ($($f.Pillar), $($f.Severity)). Rule $($f.Rule)$(if ($f.Policy) { "; Azure Policy: $($f.Policy)" })$(if ($f.PSRule) { "; PSRule for Azure: $($f.PSRule)" }).

## Decision

The risk is accepted$(if ($Reason) { ": $Reason" } else { '.' })

## Consequences

- Review by: $($ReviewBy.ToString('yyyy-MM-dd', [cultureinfo]::InvariantCulture))
- The fix, when it is due: $($f.Remediation) ($($f.Link))
- Pipelines pass Test-AACArchitectureDesign with -Accept '$($f.Rule)$(if ($f.NodeId) { ":$($f.NodeId)" })' until then.
"@
            & $write "Accept risk $($f.Rule) on $($f.Component)" 'Accepted (risk)' $body
        }

        # The index, with the open decisions and assumptions.
        $index = [System.Text.StringBuilder]::new()
        $null = $index.AppendLine("# Architecture decisions - $($model.Name)").AppendLine()
        $null = $index.AppendLine('| # | Decision | Status |').AppendLine('| --- | --- | --- |')
        foreach ($r in $records) { $null = $index.AppendLine("| $($r.Number) | [$($r.Title)]($($r.File)) | $($r.Status) |") }
        $null = $index.AppendLine().AppendLine('## Open decisions').AppendLine()
        if (@($model.Open).Count) { foreach ($id in @($model.Open)) { $q = @($catalog.Questions | Where-Object Id -EQ $id)[0]; $null = $index.AppendLine("- **$id** $(if ($q) { $q.Text }) - the default ($($a[$id])) was used until it is decided.") } }
        else { $null = $index.AppendLine('None.') }
        $assumed = @($catalog.Questions | Where-Object { @($model.Assumed) -contains $_.Id })
        $null = $index.AppendLine().AppendLine('## Assumptions (defaults no one answered)').AppendLine()
        if ($assumed.Count) { foreach ($q in $assumed) { $null = $index.AppendLine("- **$($q.Id)** $($q.Text) - $($a[$q.Id])") } } else { $null = $index.AppendLine('None.') }
        $null = $index.Append($footer)
        $readme = Join-Path -Path $folder -ChildPath 'README.md'
        [System.IO.File]::WriteAllText($readme, $index.ToString(), [System.Text.UTF8Encoding]::new($false))
        Get-Item -LiteralPath $readme
    }
}
